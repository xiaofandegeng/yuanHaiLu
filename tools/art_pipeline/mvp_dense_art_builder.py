        draw.rectangle((1, 1, 62, 62), fill=P["ink_black"])
        draw.rectangle((4, 4, 59, 59), fill=P["wood_dark"])
        for py in (12, 18, 24, 30):
            draw.ellipse((43, py, 49, py + 5), fill=P["vermilion_bright"])
