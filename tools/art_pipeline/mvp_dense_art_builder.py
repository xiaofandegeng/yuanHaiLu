def _draw_frame(layers, ox, oy, direction, animation, frame_index, frame_count):
    stride, bob, sway, attack = _motion(animation, frame_index, frame_count)
    cx = 8 + (attack if direction == "right" else -attack if direction == "left" else 0)
    cy = bob

    if direction == "down":
        face_m = HERO_FRONT_FACE
        hair_m = HERO_FRONT_HAIR
        outfit_m = HERO_FRONT_OUTFIT
        acc_m = HERO_FRONT_ACCESSORY
        weap_m = HERO_FRONT_WEAPON
    elif direction == "up":
        face_m = HERO_BACK_FACE
        hair_m = HERO_BACK_HAIR
        outfit_m = HERO_BACK_OUTFIT
        acc_m = HERO_BACK_ACCESSORY
        weap_m = HERO_BACK_WEAPON
    elif direction == "left":
        face_m = HERO_LEFT_FACE
        hair_m = HERO_LEFT_HAIR
        outfit_m = HERO_LEFT_OUTFIT
        acc_m = HERO_LEFT_ACCESSORY
        weap_m = HERO_LEFT_WEAPON
    else:  # right
        face_m = HERO_RIGHT_FACE
        hair_m = HERO_RIGHT_HAIR
        outfit_m = HERO_RIGHT_OUTFIT
        acc_m = HERO_RIGHT_ACCESSORY
        weap_m = HERO_RIGHT_WEAPON

    # 渲染各个分层
    _render_matrix(layers["accessory"], ox + cx, oy + cy, acc_m)
    _render_matrix(layers["body"], ox + cx, oy + cy, HERO_FRONT_BODY)
    _render_matrix(layers["outfit"], ox + cx, oy + cy, outfit_m)
    _render_matrix(layers["face"], ox + cx, oy + cy, face_m)
    _render_matrix(layers["hair"], ox + cx, oy + cy, hair_m)
    _render_matrix(layers["weapon"], ox + cx, oy + cy, weap_m)


def _new_sheet(size):
    return {name: Image.new("RGBA", size, P["clear"]) for name in MODULE_NAMES}


def _write_if_changed(image, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        with Image.open(path) as existing:
            if existing.convert("RGBA").size == image.size and existing.convert("RGBA").tobytes() == image.tobytes():
                return False
    image.save(path, format="PNG", optimize=False, compress_level=9)
    return True


def _write_text_if_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


